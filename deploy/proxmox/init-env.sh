#!/usr/bin/env bash
# Write the compose-root .env for this deployment, generating every secret on
# this machine. Refuses to overwrite an existing .env: rotating these values
# invalidates sessions, stored provider keys and download links
# (docs/deployment.md), so that is never done implicitly.
#
# Usage: deploy/proxmox/init-env.sh <web host> <files host> <bind ip>
#   e.g. deploy/proxmox/init-env.sh mike.example.com mike-files.example.com 10.10.10.6
set -euo pipefail

web_host="${1:?web host, e.g. mike.example.com}"
files_host="${2:?files host, e.g. mike-files.example.com}"
bind_ip="${3:?address the web app and storage listen on}"

root="$(cd "$(dirname "$0")/../.." && pwd)"
env_file="$root/.env"
if [ -e "$env_file" ]; then
  echo "refusing to overwrite $env_file" >&2
  exit 1
fi

b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }

jwt_secret="$(openssl rand -hex 32)"
now="$(date +%s)"
exp="$((now + 10 * 365 * 86400))"
# An HS256 JWT for a Supabase role, signed with the secret above.
supabase_key() {
  local header payload signature
  header="$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)"
  payload="$(printf '{"iss":"supabase","role":"%s","iat":%s,"exp":%s}' "$1" "$now" "$exp" | b64url)"
  signature="$(printf '%s.%s' "$header" "$payload" \
    | openssl dgst -sha256 -hmac "$jwt_secret" -binary | b64url)"
  printf '%s.%s.%s' "$header" "$payload" "$signature"
}

umask 077
cat > "$env_file" <<EOF
# Generated by deploy/proxmox/init-env.sh. Holds secrets: keep it mode 600 and
# out of git (the repository's .gitignore already excludes .env).
COMPOSE_FILE=docker-compose.yml:deploy/proxmox/docker-compose.override.yml

NODE_ENV=production
MIKE_BIND_IP=$bind_ip
FRONTEND_URL=https://$web_host
API_PUBLIC_URL=https://$web_host/api
R2_PUBLIC_ENDPOINT_URL=https://$files_host

# Accounts are created with deploy/proxmox/add-user.sh; nobody can sign up.
GOTRUE_DISABLE_SIGNUP=true
GOTRUE_MAILER_AUTOCONFIRM=false
GOTRUE_EXTERNAL_GOOGLE_ENABLED=false

# No error reports leave this host.
SENTRY_DISABLED=true

JWT_SECRET=$jwt_secret
SUPABASE_PUBLISHABLE_KEY=$(supabase_key anon)
SUPABASE_SECRET_KEY=$(supabase_key service_role)

STORAGE_ACCESS_KEY=mike$(openssl rand -hex 6)
STORAGE_SECRET_KEY=$(openssl rand -hex 32)

DOWNLOAD_SIGNING_SECRET=$(openssl rand -hex 32)
USER_API_KEYS_ENCRYPTION_SECRET=$(openssl rand -hex 32)

CLAUDE_CODE_SUBSCRIPTION=on
EOF
chmod 600 "$env_file"
echo "wrote $env_file"
